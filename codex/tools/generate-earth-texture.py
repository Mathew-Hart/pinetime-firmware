#!/usr/bin/env python3
"""Project NASA's Blue Marble into the fixed Earth face camera and emit flash data.

Host-only asset generation; no firmware, phone, Bluetooth or upload actions.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import urllib.request

from PIL import Image, __version__ as pillow_version

SOURCE_URL = "https://eoimages.gsfc.nasa.gov/images/imagerecords/57000/57735/land_ocean_ice_cloud_2048.jpg"
SOURCE_SHA256 = "fb67ac030214c1891994c8f976e7f6c9cd5b0f21586aba8567250781a4fe708e"
ARTICLE_URL = "https://science.nasa.gov/earth/earth-observatory/the-blue-marble-true-color-global-imagery-at-1km-resolution/"
DIAMETER = 206
LATITUDE = 20.0
LONGITUDE = -100.0
ORIGINAL_GENERATOR_SHA256 = "ebd1e6bfe8121c435caf7f6210d9c07806b464cfc3eadd2c27990d2dd4d4e408"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def project(source: Image.Image) -> Image.Image:
    texture = source.convert("RGB")
    width, height = texture.size
    pixels = texture.load()
    lat, lon = math.radians(LATITUDE), math.radians(LONGITUDE)
    east = (-math.sin(lon), math.cos(lon), 0)
    north = (-math.sin(lat) * math.cos(lon), -math.sin(lat) * math.sin(lon), math.cos(lat))
    viewer = (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat))
    # Supersample projection for the limb and coastlines, then reduce to the
    # exact firmware pixel grid. No lighting is baked into this texture.
    size = DIAMETER * 2
    output = Image.new("RGB", (size, size))
    target = output.load()
    radius = size / 2
    for y in range(size):
        ny = (radius - y - .5) / radius
        for x in range(size):
            nx = (x + .5 - radius) / radius
            r2 = nx * nx + ny * ny
            if r2 > 1:
                continue
            nz = math.sqrt(1 - r2)
            world = tuple(nx * east[i] + ny * north[i] + nz * viewer[i] for i in range(3))
            longitude = math.atan2(world[1], world[0])
            latitude = math.asin(max(-1, min(1, world[2])))
            u = (longitude / (2 * math.pi) + .5) * width - .5
            v = (.5 - latitude / math.pi) * height - .5
            x0, y0 = math.floor(u), math.floor(v)
            fx, fy = u - x0, v - y0
            x1, y1 = (x0 + 1) % width, min(height - 1, max(0, y0 + 1))
            x0, y0 = x0 % width, min(height - 1, max(0, y0))
            target[x, y] = tuple(round((pixels[x0, y0][i] * (1 - fx) + pixels[x1, y0][i] * fx) * (1 - fy)
                                       + (pixels[x0, y1][i] * (1 - fx) + pixels[x1, y1][i] * fx) * fy) for i in range(3))
    return output.resize((DIAMETER, DIAMETER), Image.Resampling.LANCZOS)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path)
    parser.add_argument("--check", action="store_true", help="Verify the checked-in texture without rewriting it")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    assets = root / "codex/assets/earth"
    assets.mkdir(parents=True, exist_ok=True)
    source = args.source or assets / "land_ocean_ice_cloud_2048.jpg"
    if not source.exists():
        with urllib.request.urlopen(SOURCE_URL, timeout=30) as response:
            data = response.read()
        source.write_bytes(data)
    if sha(source) != SOURCE_SHA256:
        raise ValueError("NASA source hash differs from the pinned Blue Marble texture")
    original = Image.open(source)
    if original.size != (2048, 1024):
        raise ValueError(f"Unexpected NASA texture dimensions: {original.size}")
    projected = project(original)
    projected_png = io.BytesIO()
    projected.save(projected_png, format="PNG")
    indexed = projected.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = indexed.getpalette()
    palette565 = [(palette[i] >> 3) << 11 | (palette[i + 1] >> 2) << 5 | (palette[i + 2] >> 3) for i in range(0, 768, 3)]
    indices = indexed.tobytes()
    assert len(indices) + len(palette565) * 2 == 42948
    # Preview the exact RGB565 palette that the watch will use.
    decoded_palette = []
    for value in palette565:
        decoded_palette.extend(((value >> 11 & 31) * 255 // 31, (value >> 5 & 63) * 255 // 63, (value & 31) * 255 // 31))
    indexed.putpalette(decoded_palette)
    indexed_png = io.BytesIO()
    indexed.convert("RGB").save(indexed_png, format="PNG")
    header = root / "src/displayapp/screens/EarthTexture.h"
    lines = ["#pragma once", "", "// Generated by tools/generate-earth-texture.py. NASA Blue Marble2002.",
             "// Source credit and reproducibility receipt: assets/earth/source.json.", "#include <array>", "#include <cstdint>", "",
             "namespace Pinetime::Applications::Screens::EarthTexture {", "  inline constexpr uint16_t Diameter = 206;",
             "  inline constexpr std::array<uint16_t, 256> Palette {", ]
    for start in range(0, len(palette565), 16):
        lines.append("    " + ", ".join(f"0x{value:04x}" for value in palette565[start:start + 16]) + ",")
    lines += ["  };", "", "  inline constexpr std::array<uint8_t, Diameter * Diameter> Pixels {"]
    for start in range(0, len(indices), 32):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in indices[start:start + 32]) + ",")
    lines += ["  };", "  static_assert(Pixels.size() + Palette.size() * sizeof(uint16_t) == 42948);", "}", ""]
    header_bytes = "\n".join(lines).encode("utf-8")
    receipt = {"source_url": SOURCE_URL, "article_url": ARTICLE_URL,
               "credit": "NASA Goddard Space Flight Center; image by Reto Stöckli, enhancements by Robert Simmon.",
               "source_description": "Blue Marble2002 land surface, ocean color, sea ice and cloud composite; historical imagery, not live clouds.",
               "usage_reference": "NASA article states the images are freely available to educators, scientists, museums and the public.",
               "source_sha256": sha(source), "source_bytes": source.stat().st_size, "source_size": list(original.size),
               "projection": {"type": "orthographic", "center_longitude_deg": LONGITUDE, "center_latitude_deg": LATITUDE,
                              "axes": "+X screen right/east; +Y screen up/north; +Z toward viewer", "diameter_px": DIAMETER,
                              "supersampling": 2, "baked_lighting": False},
               "encoding": {"indices": "8-bit", "palette": "256 RGB565 colors", "texture_bytes": len(indices),
                            "palette_bytes": len(palette565) * 2, "total_flash_data_bytes": 42948},
               "pillow_version": pillow_version,
               "generator_sha256": ORIGINAL_GENERATOR_SHA256,
               "generator_sha256_role": "Original generator used for the checked-in texture before publication path adaptation",
               "portable_generator": {"path": "codex/tools/generate-earth-texture.py", "sha256": sha(Path(__file__)),
                                      "note": "Repository-relative paths and check mode; projection, quantization and header bytes unchanged"},
               "header_sha256": hashlib.sha256(header_bytes).hexdigest(),
               "projected_png_sha256": hashlib.sha256(projected_png.getvalue()).hexdigest(),
               "indexed_png_sha256": hashlib.sha256(indexed_png.getvalue()).hexdigest(), "phone_actions": []}
    if args.check:
        expected = json.loads((assets / "source.json").read_text())
        if header.read_bytes() != header_bytes:
            raise ValueError("Generated texture differs from the checked-in firmware header")
        for field in ["source_sha256", "header_sha256", "projected_png_sha256", "indexed_png_sha256"]:
            if receipt[field] != expected[field]:
                raise ValueError(f"Generated asset hash differs: {field}")
        print(json.dumps({"result": "PASS", "checked_in_texture_unchanged": True,
                          "header_sha256": receipt["header_sha256"]}, indent=2))
        return
    header.write_bytes(header_bytes)
    (assets / "earth-projected.png").write_bytes(projected_png.getvalue())
    (assets / "earth-indexed.png").write_bytes(indexed_png.getvalue())
    (assets / "source.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
